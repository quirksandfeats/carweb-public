#!/usr/bin/env node
// Writes app/photo_skips.js: stored generation photos the site must not show.
// Wikipedia marks some as non-free (fair use): they may be shown on Wikipedia
// itself, not here. Others have names cut short in an old read ("File:1913"),
// which load nothing. A card with a skipped photo falls back to its article's
// own image. Nothing here is written by hand.
//
//   node scripts/photo_skips.js
const fs = require("fs"), path = require("path"), https = require("https");
const ROOT = path.join(__dirname, "..");
const post = body => new Promise((res, rej) => {
  const req = https.request("https://en.wikipedia.org/w/api.php", { method: "POST", headers: {
    "User-Agent": "CarWebEngineSweep/1.0 (https://github.com/quirksandfeats/carweb-public)", "Content-Type": "application/x-www-form-urlencoded" } }, r => {
    let d = ""; r.setEncoding("utf8"); r.on("data", c => d += c); r.on("end", () => { try { res(JSON.parse(d)); } catch (e) { rej(e); } });
  });
  req.on("error", rej); req.end(body);
});
(async () => {
  const text = fs.readFileSync(path.join(ROOT, "app/llm_families.json"), "utf-8");
  const files = [...new Set([...text.matchAll(/"wikiFile":\s*("(?:[^"\\]|\\.)*")/g)].map(m => JSON.parse(m[1])))].sort();
  const title = f => "File:" + String(f).replace(/^file:/i, "");
  const skip = {};
  for (let i = 0; i < files.length; i += 50) {
    const batch = files.slice(i, i + 50);
    const r = await post(new URLSearchParams({ action: "query", format: "json", formatversion: 2, prop: "imageinfo",
      iiprop: "extmetadata", iiextmetadatafilter: "NonFree|LicenseShortName", titles: batch.map(title).join("|") }).toString());
    const norm = new Map(((r.query || {}).normalized || []).map(x => [x.to, x.from]));
    ((r.query || {}).pages || []).forEach(p => {
      const asked = norm.get(p.title) || p.title;
      const f = batch.find(b => title(b) === asked);
      if (!f) return;
      const md = ((p.imageinfo || [])[0] || {}).extmetadata || {};
      if (p.missing && !p.known) skip[f] = "no such file";
      else if (md.NonFree && String(md.NonFree.value) === "true") skip[f] = "non-free: " + ((md.LicenseShortName || {}).value || "fair use");
    });
  }
  const keys = Object.keys(skip).sort();
  fs.writeFileSync(path.join(ROOT, "app/photo_skips.js"),
    "// Generated by scripts/photo_skips.js. Do not edit: change the rule.\nwindow.PHOTO_SKIPS = {\n" +
    keys.map(k => "  " + JSON.stringify(k) + ": " + JSON.stringify(skip[k]) + ",").join("\n") + "\n};\n");
  console.log(`${files.length} photos checked, ${keys.length} skipped`);
})().catch(e => { console.error(e); process.exit(1); });
